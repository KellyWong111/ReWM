#!/usr/bin/env python3
"""Check hashes and reject unexpected release files (standard library only)."""
import argparse
import hashlib
from pathlib import Path, PurePosixPath
import re


def verify(root, strict=False):
    root = Path(root).resolve()
    manifest = root / 'SHA256SUMS'
    if manifest.is_symlink() or not manifest.is_file():
        raise ValueError('SHA256SUMS must be a regular file')
    expected = {}
    for line_number, entry in enumerate(manifest.read_text().splitlines(), 1):
        if '  ' not in entry:
            raise ValueError(f'Malformed checksum entry at line {line_number}')
        digest, name = entry.split('  ', 1)
        path = PurePosixPath(name)
        if (not re.fullmatch(r'[0-9a-f]{64}', digest) or not name
                or path.is_absolute() or '..' in path.parts
                or str(path) != name or '\\' in name or name == 'SHA256SUMS'):
            raise ValueError(f'Invalid checksum entry at line {line_number}')
        if name in expected:
            raise ValueError(f'Duplicate checksum entry: {name}')
        expected[name] = digest
    if not expected:
        raise ValueError('Empty checksum manifest')
    actual = set()
    for path in root.rglob('*'):
        name = path.relative_to(root).as_posix()
        if path.is_symlink():
            raise ValueError(f'Symlink is not a release artifact: {name}')
        if path.is_file():
            if name == 'SHA256SUMS':
                continue
            # Strict mode also checks bytecode generated by imports.
            if not strict and '__pycache__' in path.relative_to(root).parts and path.suffix == '.pyc':
                continue
            actual.add(name)
    problems = []
    missing = set(expected) - actual
    extra = actual - set(expected)
    if missing:
        problems.append('Missing files: ' + ', '.join(sorted(missing)))
    if extra:
        problems.append('Unexpected files: ' + ', '.join(sorted(extra)))
    changed = [name for name in sorted(set(expected) & actual)
               if hashlib.sha256((root / name).read_bytes()).hexdigest() != expected[name]]
    if changed:
        problems.append('Checksum mismatch: ' + ', '.join(changed))
    if problems:
        raise ValueError('\n'.join(problems))
    return len(expected)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--strict', action='store_true', help='Also reject generated Python bytecode caches.')
    args = parser.parse_args()
    try:
        count = verify(Path(__file__).resolve().parents[1], strict=args.strict)
    except (ValueError, OSError) as exc:
        raise SystemExit(str(exc)) from exc
    print(f'Verified {count} packaged files; no unexpected release files.')


if __name__ == '__main__':
    main()
